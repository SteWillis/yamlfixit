"""
Ontology Exporters for YAML FixIt:
1. export_to_yaml(ontology) -> Formatted, commented Ontology YAML (100% compatible with ontology.stewillis.com)
2. export_to_markdown(ontology) -> Rich Markdown Ontology & Schema Guide with Mermaid ER diagram
"""

import json
from typing import Dict, Any, List


def _yaml_quote(val: str) -> str:
    """Safely double-quotes a string for YAML output."""
    if val is None:
        return '""'
    s = str(val).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ")
    return f'"{s}"'


def export_to_yaml(ontology: Dict[str, Any]) -> str:
    """
    Renders the ontology dictionary into the clean, human-readable 6-section YAML format
    used by ontology.stewillis.com (with compact flow-style column definitions).
    """
    db = ontology.get("database", {})
    db_name = db.get("name", "MyDatabase")
    rdbms = db.get("rdbms_type", "PostgreSQL")
    db_desc = db.get("description", "Enterprise database schema ontology.")
    version = ontology.get("version", "1.0")

    lines: List[str] = [
        "# ==============================================================================",
        f"# {db_name} - Database Schema Ontology Specification",
        "# Generated by YAML FixIt Studio (yamlfixit.stewillis.com)",
        "# Ready for Neo4j Graph-RAG Text-to-SQL on ontology.stewillis.com",
        "# ==============================================================================",
        "",
        f"version: {_yaml_quote(version)}",
        "",
        "# 1. DATABASE METADATA",
        "database:",
        f"  name: {_yaml_quote(db_name)}",
        f"  rdbms_type: {_yaml_quote(rdbms)}",
        f"  description: {_yaml_quote(db_desc)}",
        "",
        "# 2. SCHEMAS / FUNCTIONAL MODULES",
        "schemas:"
    ]

    schemas = ontology.get("schemas", [])
    if not schemas:
        lines.append('  - name: "public"')
        lines.append('    description: "Default database schema"')
    else:
        for s in schemas:
            lines.append(f"  - name: {_yaml_quote(s.get('name', 'public'))}")
            lines.append(f"    description: {_yaml_quote(s.get('description', ''))}")

    lines.append("")
    lines.append("# 3. BUSINESS CONCEPTS (Glossary terms for AI reasoning)")
    concepts = ontology.get("business_concepts", [])
    if not concepts:
        lines.append("business_concepts: []")
    else:
        lines.append("business_concepts:")
        for bc in concepts:
            lines.append(f"  - name: {_yaml_quote(bc.get('name', ''))}")
            lines.append(f"    schema: {_yaml_quote(bc.get('schema', 'public'))}")
            lines.append(f"    table: {_yaml_quote(bc.get('table', ''))}")
            lines.append(f"    key_column: {_yaml_quote(bc.get('key_column', 'id'))}")
            lines.append(f"    description: {_yaml_quote(bc.get('description', ''))}")
            lines.append("")

    if lines[-1] != "":
        lines.append("")
    lines.append("# 4. TABLES & COLUMNS")
    tables = ontology.get("tables", [])
    if not tables:
        lines.append("tables: []")
    else:
        lines.append("tables:")
        for t in tables:
            lines.append(f"  - schema: {_yaml_quote(t.get('schema', 'public'))}")
            lines.append(f"    name: {_yaml_quote(t.get('name', ''))}")
            lines.append(f"    description: {_yaml_quote(t.get('description', ''))}")
            cols = t.get("columns", [])
            if not cols:
                lines.append("    columns: []")
            else:
                lines.append("    columns:")
                for c in cols:
                    parts = [
                        f"name: {_yaml_quote(c.get('name', ''))}",
                        f"type: {_yaml_quote(c.get('type', 'varchar(255)'))}"
                    ]
                    if c.get("pk"):
                        parts.append("pk: true")
                    fk = c.get("fk")
                    if fk and isinstance(fk, dict) and fk.get("target_table"):
                        tgt_t = _yaml_quote(fk.get("target_table", ""))
                        tgt_c = _yaml_quote(fk.get("target_column", "id"))
                        parts.append(f"fk: {{ target_table: {tgt_t}, target_column: {tgt_c} }}")
                    parts.append(f"description: {_yaml_quote(c.get('description', ''))}")
                    lines.append(f"      - {{ {', '.join(parts)} }}")
            lines.append("")

    if lines[-1] != "":
        lines.append("")
    lines.append("# 5. SEMANTIC & FOREIGN KEY RELATIONSHIPS (Bidirectional for AI Reasoning)")
    rels = ontology.get("semantic_relationships", [])
    if not rels:
        lines.append("semantic_relationships: []")
    else:
        lines.append("semantic_relationships:")
        for r in rels:
            lines.append(f"  - name: {_yaml_quote(r.get('name', 'REFERENCES'))}")
            if r.get("inverse_name"):
                lines.append(f"    inverse_name: {_yaml_quote(r.get('inverse_name'))}")
            lines.append(f"    source_table: {_yaml_quote(r.get('source_table', ''))}")
            lines.append(f"    target_table: {_yaml_quote(r.get('target_table', ''))}")
            lines.append(f"    source_column: {_yaml_quote(r.get('source_column', ''))}")
            lines.append(f"    target_column: {_yaml_quote(r.get('target_column', 'id'))}")
            lines.append(f"    cardinality: {_yaml_quote(r.get('cardinality', 'N:1'))}")
            if r.get("forward_description"):
                lines.append(f"    forward_description: {_yaml_quote(r.get('forward_description'))}")
            if r.get("reverse_description"):
                lines.append(f"    reverse_description: {_yaml_quote(r.get('reverse_description'))}")
            lines.append(f"    description: {_yaml_quote(r.get('description', ''))}")
            lines.append("")

    if lines[-1] != "":
        lines.append("")
    lines.append("# 6. COMMON JOIN PATHS (Optional hints for AI reasoning)")
    joins = ontology.get("common_join_paths", [])
    if not joins:
        lines.append("common_join_paths: []")
    else:
        lines.append("common_join_paths:")
        for jp in joins:
            lines.append(f"  - name: {_yaml_quote(jp.get('name', 'Join Query'))}")
            lines.append(f"    description: {_yaml_quote(jp.get('description', ''))}")
            lines.append("    sql: |")
            sql_text = str(jp.get("sql", "")).strip()
            for s_line in sql_text.splitlines():
                lines.append(f"      {s_line}")
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def export_to_markdown(ontology: Dict[str, Any]) -> str:
    """
    Renders the ontology dictionary into a comprehensive Markdown Ontology & Schema Guide
    modeled after pqbookings_ontology.md (including Mermaid erDiagram, grouped entity dictionary,
    business concepts glossary, and SQL join templates).
    """
    db = ontology.get("database", {})
    db_name = db.get("name", "MyDatabase")
    rdbms = db.get("rdbms_type", "PostgreSQL")
    db_desc = db.get("description", "Database schema ontology.")
    schemas = ontology.get("schemas", [])
    tables = ontology.get("tables", [])
    rels = ontology.get("semantic_relationships", [])
    concepts = ontology.get("business_concepts", [])
    joins = ontology.get("common_join_paths", [])

    md: List[str] = [
        f"# {db_name} Database Ontology & Schema Guide",
        "",
        f"This document defines the schema ontology of the **{db_name}** (`{rdbms}`) database. {db_desc}",
        "It serves as semantic knowledge for LLMs (Gemini) and Graph-RAG (Neo4j) to translate natural language questions into accurate SQL queries.",
        "",
        "---",
        "",
        "## 1. Domains & ER Diagram Overview",
        "",
        "```mermaid",
        "erDiagram"
    ]

    # Add relationships to Mermaid erDiagram
    if rels:
        for r in rels:
            src_short = str(r.get("source_table", "")).split(".")[-1].upper()
            tgt_short = str(r.get("target_table", "")).split(".")[-1].upper()
            card = str(r.get("cardinality", "N:1")).upper()
            rel_label = str(r.get("name", "links")).lower().replace("_", " ")
            if card == "1:1":
                connector = "||--||"
            elif card == "1:N":
                connector = "||--o{"
            else:
                # Default N:1: target (parent 1) ||--o{ source (child N)
                md.append(f'    {tgt_short} ||--o{{ {src_short} : "{rel_label}"')
                continue
            md.append(f'    {src_short} {connector} {tgt_short} : "{rel_label}"')
    else:
        for t in tables:
            t_upper = str(t.get("name", "TABLE")).upper()
            md.append(f"    {t_upper} {{")
            for c in t.get("columns", [])[:6]:
                c_type = str(c.get("type", "string")).split("(")[0].replace(" ", "_")
                pk_tag = " PK" if c.get("pk") else (" FK" if c.get("fk") else "")
                md.append(f"        {c_type} {c.get('name', 'col')}{pk_tag}")
            md.append("    }")

    md.extend([
        "```",
        "",
        "---",
        "",
        "## 2. Entity Dictionary & Table Specifications",
        ""
    ])

    # Group tables by schema
    schema_descriptions = {s.get("name"): s.get("description", "") for s in schemas if isinstance(s, dict)}
    grouped_tables: Dict[str, List[Dict[str, Any]]] = {}
    for t in tables:
        s_name = t.get("schema", "public")
        grouped_tables.setdefault(s_name, []).append(t)

    for idx, (s_name, s_tables) in enumerate(grouped_tables.items(), start=1):
        s_desc = schema_descriptions.get(s_name, "")
        md.append(f"### 2.{idx} Schema: `{s_name}`" + (f" — {s_desc}" if s_desc else ""))
        md.append("")
        for t in s_tables:
            t_name = t.get("name", "table")
            t_desc = t.get("description", "")
            cols = t.get("columns", [])
            pks = [c["name"] for c in cols if c.get("pk")]
            fks = [
                f"`{c['name']}` → `{c['fk']['target_table']}({c['fk'].get('target_column', 'id')})`"
                for c in cols if isinstance(c.get("fk"), dict) and c["fk"].get("target_table")
            ]

            md.append(f"#### `{t_name}`")
            if t_desc:
                md.append(f"* **Description**: {t_desc}")
            if pks:
                md.append(f"* **Primary Key**: `{', '.join(pks)}`")
            if fks:
                md.append("* **Foreign Keys**:")
                for fk_str in fks:
                    md.append(f"  * {fk_str}")
            md.append("* **Columns**:")
            for c in cols:
                badges = [f"`{c.get('type', 'varchar')}`"]
                if c.get("pk"):
                    badges.append("PK")
                if c.get("fk"):
                    badges.append("FK")
                badge_str = ", ".join(badges)
                c_desc = c.get("description", "")
                md.append(f"  * `{c.get('name')}` ({badge_str})" + (f": {c_desc}" if c_desc else ""))
            md.append("")

    if rels:
        md.extend([
            "---",
            "",
            "## 3. Bidirectional Semantic Relationships (For AI / LLM Reasoning)",
            "",
            "| Join (`Source → Target`) | Forward (`Source → Target`) | Reverse (`Target → Source`) |",
            "| :--- | :--- | :--- |"
        ])
        for r in rels:
            src_full = r.get("source_table", "")
            tgt_full = r.get("target_table", "")
            src_col = r.get("source_column", "")
            tgt_col = r.get("target_column", "id")
            card = r.get("cardinality", "N:1")
            inv_card = "1:N" if card == "N:1" else ("N:1" if card == "1:N" else "1:1")
            fwd_name = r.get("name", "REFERENCES")
            inv_name = r.get("inverse_name") or f"HAS_{src_full.split('.')[-1].upper()}"
            fwd_desc = r.get("forward_description") or r.get("description", "")
            rev_desc = r.get("reverse_description") or f"{tgt_full} links back to {src_full}"
            md.append(
                f"| `{src_full}.{src_col}` = `{tgt_full}.{tgt_col}` | "
                f"**{fwd_name}** (`{card}`): {fwd_desc} | "
                f"**{inv_name}** (`{inv_card}`): {rev_desc} |"
            )
        md.append("")

    if concepts:
        md.extend([
            "---",
            "",
            "## 4. Business Concepts Glossary",
            "",
            "| Concept | Mapped Table | Key Column | Description |",
            "| :--- | :--- | :--- | :--- |"
        ])
        for bc in concepts:
            md.append(
                f"| **{bc.get('name', '')}** | `{bc.get('schema', 'public')}.{bc.get('table', '')}` "
                f"| `{bc.get('key_column', 'id')}` | {bc.get('description', '')} |"
            )
        md.append("")

    if joins:
        md.extend([
            "---",
            "",
            "## 5. Standard Join Templates for AI SQL Generation",
            ""
        ])
        for j_idx, jp in enumerate(joins, start=1):
            md.append(f"### {j_idx}. {jp.get('name', 'Join Query')}")
            if jp.get("description"):
                md.append(f"{jp['description']}")
            md.append("```sql")
            md.append(str(jp.get("sql", "")).strip())
            md.append("```")
            md.append("")

    return "\n".join(md).rstrip() + "\n"


def export_to_sql_ddl(ontology: Dict[str, Any]) -> str:
    """
    Generates executable SQL DDL (CREATE TABLE + Foreign Key constraints)
    tailored to the selected RDBMS dialect (PostgreSQL, MySQL, Microsoft SQL Server, Redshift).
    """
    db = ontology.get("database", {})
    db_name = db.get("name", "MyDatabase")
    rdbms = str(db.get("rdbms_type", "PostgreSQL"))
    low_rdbms = rdbms.lower()
    is_mysql = "mysql" in low_rdbms
    is_mssql = "sql server" in low_rdbms or "mssql" in low_rdbms

    schemas = ontology.get("schemas", [])
    tables = ontology.get("tables", [])
    rels = ontology.get("semantic_relationships", [])

    lines: List[str] = [
        "-- =============================================================================",
        f"-- {db_name} - Executable SQL DDL Schema",
        f"-- Dialect: {rdbms}",
        "-- Generated by YAML FixIt Studio (yamlfixit.stewillis.com)",
        "-- =============================================================================",
        ""
    ]

    if not is_mysql:
        for s in schemas:
            s_name = s.get("name", "public")
            if s_name and s_name.lower() not in ("public", "dbo"):
                if is_mssql:
                    lines.append(f"IF NOT EXISTS (SELECT * FROM sys.schemas WHERE name = '{s_name}') EXEC('CREATE SCHEMA [{s_name}]');")
                else:
                    lines.append(f"CREATE SCHEMA IF NOT EXISTS {s_name};")
        if len(lines) > 6:
            lines.append("")

    for t in tables:
        s_name = t.get("schema", "public")
        t_name = t.get("name", "table")
        t_desc = str(t.get("description", "")).replace("'", "''")
        cols = t.get("columns", [])

        if is_mysql:
            full_ident = f"`{t_name}`"
        elif is_mssql:
            full_ident = f"[{s_name}].[{t_name}]"
        else:
            full_ident = f"{s_name}.{t_name}"

        if t_desc:
            lines.append(f"-- Table: {s_name}.{t_name} — {t.get('description', '')}")

        lines.append(f"CREATE TABLE {full_ident} (")
        col_defs = []
        pks = []
        for c in cols:
            c_name = c.get("name", "col")
            c_type = c.get("type", "varchar(255)")
            is_pk = bool(c.get("pk"))
            c_desc = str(c.get("description", "")).replace("'", "''")

            if is_mysql:
                q_col = f"`{c_name}`"
            elif is_mssql:
                q_col = f"[{c_name}]"
            else:
                q_col = c_name

            null_clause = " NOT NULL" if is_pk else ""
            comment_clause = f" COMMENT '{c_desc}'" if (is_mysql and c_desc) else ""
            col_defs.append(f"    {q_col} {c_type.upper()}{null_clause}{comment_clause}")
            if is_pk:
                pks.append(q_col)

        if pks:
            col_defs.append(f"    PRIMARY KEY ({', '.join(pks)})")

        lines.append(",\n".join(col_defs))
        if is_mysql and t_desc:
            lines.append(f") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='{t_desc}';")
        else:
            lines.append(");")
        lines.append("")

    if rels:
        lines.append("-- Foreign Key Constraints")
        for idx, r in enumerate(rels, start=1):
            src_tbl = r.get("source_table", "")
            tgt_tbl = r.get("target_table", "")
            src_col = r.get("source_column", "")
            tgt_col = r.get("target_column", "id")
            rel_name = r.get("name", f"FK_{idx}").lower()
            fk_name = f"fk_{src_tbl.split('.')[-1]}_{src_col}_{idx}"

            if is_mysql:
                s_ident = f"`{src_tbl.split('.')[-1]}`"
                t_ident = f"`{tgt_tbl.split('.')[-1]}`"
                sc_ident = f"`{src_col}`"
                tc_ident = f"`{tgt_col}`"
            elif is_mssql:
                sp = src_tbl.split(".", 1)
                tp = tgt_tbl.split(".", 1)
                s_ident = f"[{sp[0]}].[{sp[-1]}]"
                t_ident = f"[{tp[0]}].[{tp[-1]}]"
                sc_ident = f"[{src_col}]"
                tc_ident = f"[{tgt_col}]"
            else:
                s_ident = src_tbl
                t_ident = tgt_tbl
                sc_ident = src_col
                tc_ident = tgt_col

            lines.append(
                f"ALTER TABLE {s_ident} ADD CONSTRAINT {fk_name} "
                f"FOREIGN KEY ({sc_ident}) REFERENCES {t_ident} ({tc_ident});"
            )
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"

